def pop_result(job_id: str, subfolder: str, filename: str) -> Path | None:
    clean_job = ntpath.basename(str(job_id).replace("\\", "/").strip())
    if not clean_job or clean_job != job_id or ".." in job_id:
        return None
    base = (_result_dir / clean_job).resolve()
    if not base.is_relative_to(_result_dir.resolve()) or not base.exists():
        return None
    clean_subfolder = ntpath.basename(str(subfolder).replace("\\", "/").strip()) if subfolder else ""
    clean_filename = ntpath.basename(str(filename).replace("\\", "/").strip())
    if not clean_filename or clean_filename != filename or ".." in filename:
        return None
    want_flat = (clean_subfolder + "/" if clean_subfolder else "") + clean_filename
    for cand in (base / clean_filename, base / want_flat.replace("/", "_")):
        cand_res = cand.resolve()
        if cand_res.is_relative_to(base) and cand_res.exists():
            return cand_res
    # suffix match (Comfy subfolders get flattened with underscores)
    flat = want_flat.replace("/", "_")
    for p in base.rglob("*"):
        if p.is_file() and p.resolve().is_relative_to(base) and (p.name == clean_filename or p.name.endswith(flat)
                            or flat.endswith(p.name)):
            return p
    return None


# ------------------------------------------------------- remote client
_NODE_TTL_S = 600.0          # a worker's node set changes only on restart
_node_cache: dict[str, tuple[float, frozenset[str]]] = {}
_node_lock = threading.Lock()


class RemoteWorkerClient:
    """Duck-typed renderer.ComfyClient that executes on a worker PC.

    queue_prompt() sends the whole workflow envelope to the agent; wait_for()
    polls the agent (NOT ComfyUI) ; upload_image() posts into the worker's
    ComfyUI input dir under the SAME filename so LoadImage nodes resolve;
    download() copies from the results the agent already pushed back to us.
    """

    def __init__(self, wid: str, timeout: int = 60) -> None:
        self.wid = wid
        self.timeout = timeout
        row = get(wid) or {}
        # A worker registered from a cloud box (Colab) advertises a scheme-ful
        # base (mesh/tunnel/serve URL) — use it verbatim; the legacy LAN case
        # stays host:port with the historical http:// prefix.
        raw_host = str(row.get("host") or "127.0.0.1")
        if "://" in raw_host:
            self.base = raw_host.rstrip("/")
        else:
            h = raw_host.strip("[]")
            h = f"[{h}]" if ":" in h else h          # bare IPv6 literal
            self.base = f"http://{h}:{row.get('port', 8120)}"
        self.token = _shared_token()

    # -- low level ----------------------------------------------------
    def _req(self, method: str, path: str, data: dict | None = None,
             raw: bytes | None = None, content_type: str | None = None,
             timeout: int | None = None) -> Any:
        url = f"{self.base}{path}"
        _assert_dialable(self.base)
        body = None
        headers = {}
        if self.token:
            headers["X-Worker-Token"] = self.token
        if data is not None:
            body = __import__("json").dumps(data).encode()
            headers["Content-Type"] = "application/json"
        elif raw is not None:
            body = raw
            if content_type:
                headers["Content-Type"] = content_type
        req = urllib.request.Request(url, data=body, headers=headers,
                                     method=method)
        with _WORKER_OPENER.open(req, timeout=timeout or self.timeout) as r:
            payload = r.read()
        if not payload:
            return {}
        try:
            return __import__("json").loads(payload.decode())
        except Exception:
            return payload

    def upload_stream(self, path: str, src: Path, timeout: int = 7200) -> Any:
        """POST a (possibly multi-GB) file without buffering it in memory."""
        url = f"{self.base}{path}"
        _assert_dialable(self.base)
        size = src.stat().st_size
        headers = {"Content-Type": "application/octet-stream",
                   "Content-Length": str(size)}
        if self.token:
            headers["X-Worker-Token"] = self.token
        with open(src, "rb") as fh:
            req = urllib.request.Request(url, data=fh, headers=headers,
                                         method="POST")
            with _WORKER_OPENER.open(req, timeout=timeout) as r:
                payload = r.read()
        if not payload:
            return {}
        try:
            return __import__("json").loads(payload.decode())
        except Exception:
            return payload

    # -- ComfyClient parity -------------------------------------------
    def _scale(self) -> float:
        """remote jobs often land on slower cards (e.g. a Colab T4 vs the
        local 3070): workers.remote_timeout_scale stretches both the agent's
        job deadline and wait_for's so a legit slow render isn't killed."""
        try:
            return float((load_config().get("workers") or {}).get(
                "remote_timeout_scale", 1.0) or 1.0)
        except Exception:
            return 1.0

    @property
    def current_job(self) -> str:
        return getattr(self, "_job_id", "")

    def node_classes(self) -> frozenset[str] | None:
        """Node classes the worker's ComfyUI can run (cached per worker for
        _NODE_TTL_S). None when the agent cannot tell (ComfyUI still
        booting, older agent) - callers then let the job through."""
        now_s = time.time()
        with _node_lock:
            hit = _node_cache.get(self.wid)
        if hit and now_s - hit[0] < _NODE_TTL_S:
            return hit[1]
        try:
            info = self.object_info()
        except Exception as e:
            log.warning("worker %s object_info: %s", self.wid, e)
            return None
        if not isinstance(info, dict) or not info or \
                not all(isinstance(v, dict) for v in info.values()):
            return None
        classes = frozenset(info)
        with _node_lock:
            _node_cache[self.wid] = (now_s, classes)
        return classes

    def missing_nodes(self, workflow: dict) -> list[str]:
        have = self.node_classes()
        if have is None:
            return []
        need = {str(n["class_type"]) for n in workflow.values()
                if isinstance(n, dict) and n.get("class_type")}
        return sorted(need - have)

    def queue_prompt(self, workflow: dict, client_id: str | None = None) -> str:
        # Refuse up front a graph the worker's ComfyUI cannot validate (e.g.
        # an H3/LTX graph sent to a render-farm-only worker): otherwise the
        # failure surfaces only after start images were pushed, as an opaque
        # ComfyUI 400 relayed through the agent.
        missing = self.missing_nodes(workflow)
        if missing:
            more = f" (+{len(missing) - 6} more)" if len(missing) > 6 else ""
            raise RuntimeError(
                f"worker {self.wid} cannot run this graph - its ComfyUI lacks "
                f"{', '.join(missing[:6])}{more}. MiniMax H3 / LTX-2.5 graphs "
                "need a worker set up with the ComfyUI_LTX tree")
        self._job_id = uuid.uuid4().hex[:12]
        res = self._req("POST", "/job", {
            "job_id": self._job_id,
            "client_id": client_id or "studio-worker",
            "workflow": workflow,
            "timeout": int(3600 * self._scale()),
        })
        return res.get("prompt_id") or self._job_id

    def history(self, prompt_id: str) -> dict:
        # Local client returns {prompt_id: history_entry}; the agent mirrors
        # exactly that shape in its job record. The record's history is keyed
        # by the COMFY prompt id (rec["prompt_id"]), while our handle is the
        # agent job id — re-key by the handle so `handle in history` works
        # exactly like the local client.
        rec = self._req("GET", f"/job/{self.current_job or prompt_id}")
        hist = rec.get("history") or {}
        entry = None
        for key in (rec.get("prompt_id"), rec.get("comfy_prompt_id"),
                    prompt_id):
            if key and key in hist:
                entry = hist[key]
                break
        if entry is None and hist:
            entry = next(iter(hist.values()))
        return {prompt_id: entry} if entry else {}

    def system_stats(self) -> dict:
        return self._req("GET", "/gpu")

    def object_info(self) -> dict:
        return self._req("GET", "/object_info", timeout=120)

    def interrupt(self) -> None:
        # scoped: the worker's ComfyUI is dedicated to this agent
        try:
            self._req("POST", f"/cancel/{self.current_job}", {})
        except Exception as e:
            log.warning("worker %s cancel: %s", self.wid, e)

    def queue_info(self) -> dict:
        return self._req("GET", "/queue")

    def upload_image(self, local_path: Path) -> str:
        # Named after its content like the local client's uploads, so a graph
        # names the same file whichever machine renders it.
        from renderer import upload_name
        return self.upload_file(local_path, upload_name(Path(local_path).read_bytes()))

    def upload_file(self, local_path: Path, name: str | None = None) -> str:
        """Upload any file into the worker's ComfyUI input dir under `name`
        (defaults to a unique name derived from the local filename). The remote
        graph (LoadImage / VHS_LoadVideo) then resolves it by that name."""
        p = Path(local_path)
        name = name or f"{p.stem}_{uuid.uuid4().hex[:8]}{p.suffix}"
        boundary = "----kinoloom" + uuid.uuid4().hex
        body = (f"--{boundary}\r\nContent-Disposition: form-data; "
                f"name=\"image\"; filename=\"{name}\"\r\n"
                f"Content-Type: application/octet-stream\r\n\r\n").encode() + \
            p.read_bytes()
        body += f"\r\n--{boundary}\r\nContent-Disposition: form-data; " \
                f"name=\"overwrite\"\r\n\r\ntrue\r\n--{boundary}--\r\n".encode()
        self._req("POST", "/upload", raw=body,
                  content_type=f"multipart/form-data; boundary={boundary}",
                  timeout=1800)
        return name

    def wait_for(self, prompt_id: str, timeout_s: float = 3600,
                 cb=None, cancel: threading.Event | None = None) -> dict | None:
        """Poll the agent until the local history entry exists — mirrors
        renderer.ComfyClient.wait_for semantics: returns the history entry
        (even for an errored execution, so the engines' own error extraction
        works unchanged), None on timeout or once `cancel` is set. cb
        receives a /queue-shaped payload (queue_running/queue_pending)
        exactly like the local client. The deadline is stretched by
        workers.remote_timeout_scale."""
        deadline = time.time() + timeout_s * self._scale()
        while time.time() < deadline:
            if cancel is not None and cancel.is_set():
                return None
            rec = self._req("GET", f"/job/{self.current_job or prompt_id}")
            hist = rec.get("history") or {}
            # The agent's history dict is keyed by the COMFY prompt id
            # (rec["prompt_id"]), NOT by our job handle — checking only the
            # handle made wait_for poll until its 30-min timeout on every
            # single remote job (the render/upscale had long finished).
            for key in (rec.get("prompt_id"), rec.get("comfy_prompt_id"),
                        prompt_id):
                if key and key in hist:
                    return hist[key]
            if rec.get("status") == "failed":
                raise RuntimeError(rec.get("error") or "worker job failed")
            if cb:
                try:
                    cb(rec.get("queue_snapshot") or {})
                except Exception:
                    pass
            if cancel is not None:
                if cancel.wait(5):
                    return None
            else:
                time.sleep(5)
        return None

    def download(self, subfolder: str, filename: str, save_to: str | Path) -> Path:
        src = pop_result(self.current_job, subfolder, filename)
        if not src:
            raise FileNotFoundError(
                f"worker result missing: {self.current_job}/"
                f"{subfolder}/{filename}")
        dest = Path(save_to)
        dest.parent.mkdir(parents=True, exist_ok=True)
        if src != dest:
            shutil.copyfile(src, dest)
        return dest

    # -- model management (agent v1.1 endpoints) -----------------------
    # Colab-class workers pull weights on their own fat pipe; these methods
    # proxy the agent's pull-based endpoints (never bulk-push through HTTP).
    def install_url(self, spec: dict, timeout: int = 14400) -> dict:
        """spec: {path, url | hf_repo+hf_file, bytes?, sha256?} — synchronous
        single-file pull on the worker."""
        return self._req("POST", "/install_url", data=spec, timeout=timeout)

    def install_group(self, install_id: str, files: list[dict]) -> dict:
        """Kick off a background batch install; poll install_group_status."""
        return self._req("POST", "/install_group", data={
            "install_id": install_id, "files": files})

    def install_group_status(self, install_id: str) -> dict:
        return self._req("GET", f"/install_group/{install_id}", timeout=30)

    def delete_model(self, path: str) -> dict:
        import urllib.parse
        return self._req("DELETE",
                         f"/models?path={urllib.parse.quote(path)}",
                         timeout=120)

    def disk(self) -> dict:
        return self._req("GET", "/disk", timeout=30)


# -------------------------------------------------------------- routing
def client_for(worker: str | None = None, port: int | None = None):
    """The single routing decision point. 'local'/None/'' → the ordinary
    localhost ComfyClient (today's behaviour, byte for byte); anything else
    must be a registered worker id → RemoteWorkerClient."""
    if not worker or worker == "local":
        from renderer import ComfyClient
        cfg_port = (load_config().get("ensemble") or {}).get("comfyui_port", 8188)
        return ComfyClient(port or cfg_port)
    if worker == "any":
        ids = online_ids()
        if not ids:
            raise RuntimeError("worker 'any' requested but no worker is online")
        worker = ids[0]
    return RemoteWorkerClient(worker)


def resolve(worker: str | None) -> str:
    """Resolve 'any' to a concrete worker id (for queue labels)."""
    if worker != "any":
        return worker or "local"
    ids = online_ids()
    return ids[0] if ids else "local"
