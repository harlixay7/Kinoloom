# ------------------------------------------------------------------ auth
def _shared_token() -> str:
    return str((load_config().get("workers") or {}).get("shared_token") or "")


def _sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def _check_token(provided: str, row: dict | None = None) -> None:
    want = _shared_token()
    if not want:
        # Fail closed: the control room generates a token at startup, so an
        # empty one means the operator removed it deliberately.
        raise PermissionError("worker fleet token is not configured "
                              "(settings.yaml workers.shared_token)")
    if not provided or not secrets.compare_digest(
            str(provided).encode("utf-8"), want.encode("utf-8")):
        raise PermissionError("bad worker token")
    if row and row.get("token_hash") and not secrets.compare_digest(
            str(row["token_hash"]), _sha(str(provided))):
        raise PermissionError("token does not match this worker's registration")


# --------------------------------------------------------- host validation
def _ip_forbidden(ip: ipaddress.IPv4Address | ipaddress.IPv6Address) -> bool:
    """Addresses a worker may never claim: link-local (cloud metadata
    services live at 169.254.169.254), multicast, unspecified, reserved.
    Private, CGNAT/Tailscale (100.64/10) and loopback stay allowed — LAN and
    mesh workers are private by nature."""
    if isinstance(ip, ipaddress.IPv6Address) and ip.ipv4_mapped:
        ip = ip.ipv4_mapped
    return bool(ip.is_link_local or ip.is_multicast or ip.is_unspecified
                or ip.is_reserved)


def validate_worker_host(host: str) -> str:
    """Normalise and validate the host a worker advertises.

    Accepts a bare host/IP (``192.168.1.20``) or an http(s) base URL
    (``https://box.tailnet.ts.net``). Raises ValueError otherwise."""
    h = str(host or "").strip()
    if not h:
        raise ValueError("worker host is empty")
    if len(h) > 255:
        raise ValueError("worker host is too long")
    if "://" in h:
        parts = urlsplit(h)
        if parts.scheme not in ("http", "https"):
            raise ValueError(f"unsupported worker URL scheme {parts.scheme!r}")
        if parts.username or parts.password:
            raise ValueError("worker URL must not embed credentials")
        name = parts.hostname or ""
        if parts.query or parts.fragment:
            raise ValueError("worker URL must not carry a query or fragment")
    else:
        name = h
        if not re.fullmatch(r"[A-Za-z0-9.\-:\[\]]+", name):
            raise ValueError(f"invalid worker host {h!r}")
        name = name.strip("[]")
    if not name:
        raise ValueError("worker host has no hostname")
    try:
        if _ip_forbidden(ipaddress.ip_address(name)):
            raise ValueError(f"worker host {name} is not an allowed address")
    except ValueError as e:
        if "not an allowed address" in str(e):
            raise
        if not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9\-.]{0,252})", name):
            raise ValueError(f"invalid worker hostname {name!r}") from None
    return h.rstrip("/")


def _assert_dialable(base_url: str) -> None:
    """Resolve the worker's host right before dialing it and refuse
    forbidden addresses (a hostname may have been re-pointed since
    registration)."""
    name = urlsplit(base_url).hostname or ""
    try:
        infos = socket.getaddrinfo(name, None)
    except OSError:
        return                      # unresolvable: urlopen will fail cleanly
    for info in infos:
        try:
            ip = ipaddress.ip_address(str(info[4][0]).split("%", 1)[0])
        except ValueError:
            continue
        if _ip_forbidden(ip):
            raise PermissionError(f"worker host {name} resolves to a forbidden "
                                  f"address ({ip})")


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    """A worker answers its own API directly; a redirect would carry the
    fleet token to whatever host the worker (or a MITM) names."""
    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: D401
        raise urllib.error.HTTPError(req.full_url, code,
                                     f"worker redirect refused ({newurl})",
                                     headers, fp)


_WORKER_OPENER = urllib.request.build_opener(_NoRedirect())


# ------------------------------------------------------------- registry
def _slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s[:32] or "worker"


def register(name: str, host: str, port: int, token: str = "",
             gpu: dict | None = None, models: list[str] | None = None,
             capabilities: dict | None = None,
             agent_version: str = "") -> dict:
    """Called by the agent at startup (and re-called on agent restart —
    idempotent upsert keyed by slug of the name)."""
    wid = _slug(name)
    _check_token(token)
    host = validate_worker_host(host)
    port = int(port)
    if not 1 <= port <= 65535:
        raise ValueError(f"invalid worker port {port}")
    ts = now()
    with task_queue._lock, task_queue.connect() as c:
        c.execute(
            "INSERT INTO workers (id, name, host, port, token_hash, status,"
            " gpu, models, capabilities, agent_version, created,"
            " last_heartbeat) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)"
            " ON CONFLICT(id) DO UPDATE SET name=excluded.name,"
            " host=excluded.host, port=excluded.port,"
            " token_hash=excluded.token_hash, status='online',"
            " gpu=excluded.gpu, models=excluded.models,"
            " capabilities=excluded.capabilities,"
            " agent_version=excluded.agent_version,"
            " last_heartbeat=excluded.last_heartbeat",
            (wid, name, host, int(port), _sha(token) if token else "",
             "online", _j(gpu or {}), _j(models or []),
             _j(capabilities or {}), agent_version, ts, ts))
    with _node_lock:
        _node_cache.pop(wid, None)       # a (re)started agent may differ
    log.info("worker registered: %s (%s:%s)", wid, host, port)
    return {"id": wid, "name": name}


def _j(o: Any) -> str:
    return __import__("json").dumps(o, ensure_ascii=False)


def heartbeat(wid: str, token: str = "", gpu: dict | None = None,
              models: list[str] | None = None,
              agent_version: str = "") -> dict:
    row = get(wid)
    if not row:
        raise LookupError(f"unknown worker {wid}")
    _check_token(token, row)
    with task_queue._lock, task_queue.connect() as c:
        c.execute("UPDATE workers SET status='online', last_heartbeat=?,"
                  " gpu=COALESCE(NULLIF(?,''), gpu),"
                  " models=COALESCE(NULLIF(?,''), models),"
                  " agent_version=CASE WHEN ?!='' THEN ? ELSE agent_version END"
                  " WHERE id=?",
                  (now(), _j(gpu) if gpu else "", _j(models) if models else "",
                   agent_version, agent_version, wid))
    return {"ok": True, "server_time": now()}


def get(wid: str) -> dict | None:
    with task_queue.connect() as c:
        r = c.execute("SELECT * FROM workers WHERE id=?", (wid,)).fetchone()
    if not r:
        return None
    d = dict(r)
    for k in ("gpu", "models", "capabilities"):
        try:
            d[k] = __import__("json").loads(d.get(k) or ("{}" if k == "gpu" else "[]"))
        except Exception:
            pass
    return d


def list_all() -> list[dict]:
    with task_queue.connect() as c:
        rows = c.execute("SELECT * FROM workers ORDER BY name").fetchall()
    out = []
    for r in rows:
        d = dict(r)
        for k in ("gpu", "models", "capabilities"):
            try:
                d[k] = __import__("json").loads(d.get(k) or ("{}" if k == "gpu" else "[]"))
            except Exception:
                pass
        d["online"] = is_online(d)
        out.append(d)
    return out


def online_ids() -> list[str]:
    return [w["id"] for w in list_all() if w["online"]]


def is_online(w: dict) -> bool:
    """online iff heartbeat within offline_after_s (defaults 30s ×3 beats)."""
    cfg = load_config().get("workers") or {}
    grace = float(cfg.get("offline_after_s", 30) or 30)
    try:
        last = datetime.fromisoformat(w.get("last_heartbeat") or "")
    except Exception:
        return False
    return (datetime.now() - last).total_seconds() <= grace


def remove(wid: str) -> dict:
    with task_queue._lock, task_queue.connect() as c:
        c.execute("DELETE FROM workers WHERE id=?", (wid,))
    return {"ok": True, "removed": wid}


def reap_offline() -> None:
    """Periodic pass (dispatcher calls it): flip silent workers to offline
    and let the queue policy decide their running items."""
    for w in list_all():
        if w["status"] == "online" and not is_online(w):
            with task_queue._lock, task_queue.connect() as c:
                c.execute("UPDATE workers SET status='offline' WHERE id=?",
                          (w["id"],))
            log.warning("worker %s went silent — marked offline", w["id"])
            _requeue_lane(w["id"])


def _requeue_lane(lane: str) -> None:
    """Worker died with a running item: apply settings.workers.on_worker_loss."""
    policy = (load_config().get("workers") or {}).get("on_worker_loss",
                                                      "requeue_local")
    with task_queue._lock, task_queue.connect() as c:
        rows = c.execute("SELECT * FROM queue_items WHERE status='running'"
                         " AND lease=?", (lane,)).fetchall()
        for r in rows:
            it = task_queue._row_to_dict(r)
            attempts = it["attempts"] + 1
            ts = now()
            if attempts >= it["max_attempts"]:
                c.execute("UPDATE queue_items SET status='failed', attempts=?,"
                          " error='worker went offline mid-job', finished=?,"
                          " lease='', updated=? WHERE id=?",
                          (attempts, ts, ts, it["id"]))
            elif policy == "fail":
                c.execute("UPDATE queue_items SET status='failed', attempts=?,"
                          " error='worker went offline mid-job', finished=?,"
                          " lease='', updated=? WHERE id=?",
                          (attempts, ts, ts, it["id"]))
            else:
                new_worker = "local" if policy == "requeue_local" else it["worker"]
                c.execute("UPDATE queue_items SET status='queued', attempts=?,"
                          " worker=?, error='worker offline — requeued',"
                          " lease='', updated=? WHERE id=?",
                          (attempts, new_worker, ts, it["id"]))
            log.warning("lane %s died: item %s → %s", lane, it["id"], policy)


# ----------------------------------------------------- result intake
def max_result_bytes() -> int:
    try:
        mb = float((load_config().get("workers") or {}).get(
            "max_result_mb", DEFAULT_MAX_RESULT_MB))
    except (TypeError, ValueError):
        mb = DEFAULT_MAX_RESULT_MB
    return int(max(1.0, mb) * 1024 * 1024)


def store_result(job_id: str, filename: str, data: bytes | BinaryIO,
                 max_bytes: int | None = None) -> dict:
    """Agent pushes finished artefacts here; download() picks them up.

    ``data`` may be bytes or a readable binary stream; streams are copied in
    chunks (never fully buffered) and refused past ``max_bytes``. The file is
    written to a temp name and renamed, so a reader never sees a partial
    artefact."""
    clean_job = ntpath.basename(str(job_id).replace("\\", "/").strip())
    clean_filename = ntpath.basename(str(filename).replace("\\", "/").strip())
    if not clean_job or clean_job != job_id or not clean_filename or clean_filename != filename or ".." in job_id or ".." in filename:
        raise HTTPException(status_code=400, detail="Path traversal rejected: invalid job or filename")
    target_dir = (_result_dir / clean_job).resolve()
    target = (target_dir / clean_filename).resolve()
    if not target.is_relative_to(target_dir.resolve()) or not target.is_relative_to(_result_dir.resolve()):
        raise HTTPException(status_code=400, detail="Path traversal rejected: destination escapes target directory")
    limit = max_bytes if max_bytes is not None else max_result_bytes()
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=str(target.parent), prefix=".part-")
    written = 0
    try:
        with os.fdopen(fd, "wb") as out:
            if isinstance(data, (bytes, bytearray, memoryview)):
                written = len(data)
                if written > limit:
                    raise HTTPException(status_code=413, detail="result exceeds workers.max_result_mb")
                out.write(data)
            else:
                while True:
                    chunk = data.read(4 * 1024 * 1024)
                    if not chunk:
                        break
                    written += len(chunk)
                    if written > limit:
                        raise HTTPException(status_code=413, detail="result exceeds workers.max_result_mb")
                    out.write(chunk)
        if written == 0:
            raise ValueError("empty result payload")
        os.replace(tmp_name, target)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except OSError:
            pass
        raise
    return {"ok": True, "stored": str(target), "bytes": written}


