"""Worker fleet — main-side registry + remote client with ComfyClient parity.

A "worker" is a second PC running tool/worker/worker_agent.py next to its own
ComfyUI. It registers here, heartbeats GPU/model telemetry, and executes job
envelopes. RemoteWorkerClient deliberately QUACKS like renderer.ComfyClient
(queue_prompt / wait_for / upload_image / download / interrupt) so engines
route to another machine by swapping the client object — nothing else in the
render path changes. Outputs the agent pushes back land under
ROOT/temp/worker_results/{job_id}/ and download() copies them to wherever the
engine would have written them locally.

Auth: settings.workers.shared_token — one fleet-wide secret, generated by the
control room at first start (see security.ensure_secrets). register,
heartbeat and result must carry it; there is no unauthenticated mode. The
token is a single shared secret: any holder can register a worker, so treat
it like a password and rotate it (Workers page → New install token) if a
worker PC is retired or compromised.
"""
