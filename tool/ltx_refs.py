"""LTX-2.5 / H3 reference resolution: shot -> MSR slots (pic1..pic4, background).

Measured rules this module implements (LTX lab record PROVEN_CONFIGS, listed in docs/research/VIDEOLAB_ARCHIVE_INDEX.md):

* References are applied at STAGE 1 ONLY. The MSR guide appends them to the
  half-resolution latent; applying them at stage 2 stalls 8 GB cards.
* A practical run uses 2-3 references: each subject slot costs latent tokens,
  and more references of the same subject compete rather than help.
* Slot order is cast priority: main characters first, then supporting, then
  recurring (crowd characters never take a subject slot). The shot's POWER
  reference takes the next free subject slot after the characters; the
  environment always takes the `background` slot.
* A shot must never hard-fail on a missing reference. Every slot walks a
  fallback chain and is simply omitted when nothing resolves; with zero
  references the pipeline falls back to the plain text-to-video template.

TYPE DISCIPLINE (never confuse the model):
* character identity refs   <- entries typed `face`   (legacy untyped ok)
* power VFX refs            <- entries typed `power`  (only from the power's
                               own `reference_images`, never from face batches)
* environment refs          <- entries typed `environment`
A mismatch is skipped with a warning instead of being passed through.

POWER LEVELS: power entries carry an optional `level` (default = list order).
The shot's `power_level` (1..N, emitted by the story pipeline / editable per
shot) selects the entry with the highest level <= target (floor), so a 10-image
power ramps 1..10 across the film automatically.

ENVIRONMENT VARIANTS: location entries carry an optional `tag` ("arena",
"palace lobby", ...). The effective tag is the shot's `location_tag`, else the
location's `scene_tags` map for the shot's scene. No tag -> the primary entry
(today's behaviour), so untagged projects are unaffected.

Resolution order per character (first hit wins):

1. `character.reference_images` entries (primary first) — the explicit picks
   made in the Cast tab; the manifest stores the batch provenance but the
   render uses the COPY in the project refs dir so later batch edits cannot
   change a finished production line.
2. the batch still itself (`roster/datasets/face/<cid>/...`) if the copy is
   missing (e.g. the YAML was hand-edited or the project is fresh).
3. existing project picks: `refs/chars/<cid>/selected.png`, uploaded hero refs.
4. auto identity: roster face `master_*.png`, first still, roster keyframes.

Locations follow the same shape under `refs/locs/<lid>` with the environment
dataset as the batch source; powers under `refs/powers/<cid>/<pw>` with the
power dataset as the batch source.
"""
from __future__ import annotations

from pathlib import Path

from core import (ROOT, InvalidInput, is_safe_component, log_setup,
                  resolve_user_path, safe_join)

log = log_setup("ltx_refs")

SLOT_SUBJECTS = ("pic1", "pic2", "pic3", "pic4")
SLOT_SUBJECTS_H3 = ("pic1", "pic2", "pic3", "pic4", "pic5")
# Per-family subject capacity. LTX MSR is a hard 5-slot guide (4 subjects +
# background); H3 fills its ref_load_nodes sequentially (6 pictures, so 5
# subjects when an environment reference is present). The environment always
# takes the background slot first, subjects get the rest.
MAX_SUBJECTS = {"ltx25": 4, "h3": 5}
TIER_ORDER = {"main": 0, "supporting": 1, "recurring": 2, "crowd": 3}
_IMG_EXTS = (".png", ".jpg", ".jpeg", ".webp")

# Identity plates (the three framing stills generated by the character batch)
# are tagged `plate:close|medium|full` on import. The resolver picks the plate
# that matches the shot's framing so the reference's scale agrees with the
# requested shot size (measured: a mid-shot plate on a wide shot made the
# model render a wrong-sized subject).
PLATE_TAGS = ("plate:close", "plate:medium", "plate:full")
_SIZE_TO_PLATE = {
    "extreme_close_up": "close", "close_up": "close",
    "medium_close_up": "close",
    "medium": "medium", "medium_wide": "medium",
    "wide": "full", "extreme_wide": "full",
}
# nearest-framing fallback order per wanted plate (exact match is tried first)
_PLATE_NEAREST = {
    "close": ("close", "medium", "full"),
    "medium": ("medium", "close", "full"),
    "full": ("full", "medium", "close"),
}


def _plate_for_shot(shot: dict | None) -> str:
    size = str((shot or {}).get("shot_size") or "").strip().lower()
    return _SIZE_TO_PLATE.get(size, "")


def max_subjects_for(family: str | None) -> int:
    return MAX_SUBJECTS["h3"] if str(family or "").startswith("h3") else \
        MAX_SUBJECTS["ltx25"]


def _bible_dir():
    from bible import BIBLE_DIR
    return BIBLE_DIR


def _norm(s) -> str:
    return "".join(c.lower() if c.isalnum() else " " for c in str(s or "")).strip()


def _ref_entries(item: dict | None, want: str | None = None) -> list[dict]:
    """Validated `reference_images` entries, primary first, order preserved.

    `want` filters by dataset type (face / power / environment). Entries
    without a type are treated as legacy and always accepted — every picker
    made since the reference system shipped writes a type.
    """
    out = []
    for r in ((item or {}).get("reference_images") or []):
        if not isinstance(r, dict) or not r.get("file"):
            continue
        t = str(r.get("type") or "").lower()
        if want and t and t != want:
            continue
        out.append(r)
    out.sort(key=lambda r: 0 if str(r.get("role") or "").lower() == "primary" else 1)
    return out


def _ref_name(name) -> str:
    """Basename of a manifest `copied`/`file` value ("" when unusable)."""
    n = Path(str(name or "")).name
    return "" if n in (".", "..") else n


def _project_copy(pid: str, sub: str, iid: str, name: str) -> Path | None:
    # ids come from shot JSON / bible YAML (client-written): plain ids only
    if not (pid and iid and name) or not is_safe_component(str(pid)) \
            or not is_safe_component(str(iid)) or not _ref_name(name):
        return None
    p = _bible_dir() / "projects" / pid / "refs" / sub / iid / _ref_name(name)
    return p if p.is_file() else None


def _power_copy(pid: str, cid: str, pw: str, name: str) -> Path | None:
    if not (pid and cid and pw and name) or not is_safe_component(str(pid)) \
            or not is_safe_component(str(cid)) \
            or not is_safe_component(str(pw)) or not _ref_name(name):
        return None
    p = (_bible_dir() / "projects" / pid / "refs" / "powers" / cid / pw
         / _ref_name(name))
    return p if p.is_file() else None


def _batch_file(entry: dict, default_type: str) -> Path | None:
    """The batch still a manifest entry points at.

    `file` may be a plain name or a RELATIVE sub-path — the batch browsers
    hand out entries like `stills/p_000.png`, and the old check
    (`Path(f).name != f`) rejected every one of those, silently dropping every
    Video Studio reference picked from a batch (jobs ran t2v while the
    operator had attached images). Traversal-safe: type/name must be plain
    ids and safe_join refuses absolute / drive-letter / UNC paths and `..`.
    """
    t = str(entry.get("type") or default_type)
    n = str(entry.get("name") or "")
    f = str(entry.get("file") or "").strip()
    if not (n and f) or not is_safe_component(t) or not is_safe_component(n):
        return None
    base = ROOT / "roster" / "datasets" / t / n
    for root in (base, base / "stills", base / "masters"):
        try:
            safe_join(root, f)
        except InvalidInput:
            continue
        cand = root / f            # validated above; keep the unresolved form
        if cand.is_file():
            return cand
    return None


def _first_existing(paths) -> Path | None:
    for p in paths:
        if p is not None and Path(p).exists():
            return Path(p)
    return None


def _dir_images(d: Path) -> list[Path]:
    if not d.is_dir():
        return []
    return [p for p in sorted(d.iterdir())
            if p.is_file() and p.suffix.lower() in _IMG_EXTS]


def character_refs(pid: str, cid: str, char: dict | None,
                   loadout: str | None = None,
                   shot: dict | None = None) -> list[Path]:
    """Ordered IDENTITY stills for one character (face references only).

    When `loadout` names a tagged reference ("JulietWithWeapon"), that
    composite still wins: one image already carries identity + outfit +
    weapon, so the character costs exactly ONE reference slot.

    Without a loadout, the shot's framing picks the matching identity plate
    (`plate:close|medium|full` tags written by the batch import) — exact match
    first, then the nearest framing. Untagged manifests are unaffected.
    """
    entries = _ref_entries(char, want="face")
    if loadout:
        want = _norm(loadout)
        hit = next((e for e in entries if _norm(e.get("tag")) == want), None)
        if hit is None and want:
            hit = next((e for e in entries
                        if want in _norm(e.get("tag"))), None)
        if hit is not None:
            entries = [hit]
        else:
            # the named loadout has no composite still yet — fall through to
            # the identity chain (the text still describes outfit/weapon)
            log.warning("ltx_refs: %s has no reference tagged '%s' — using the "
                        "primary identity still", cid, loadout)
    elif shot is not None:
        plate = _plate_for_shot(shot)
        if plate:
            tags = {_norm(e.get("tag")): e for e in entries
                    if str(e.get("tag") or "").strip().lower()
                    .startswith("plate:")}
            hit = None
            for cand in _PLATE_NEAREST.get(plate, (plate,)):
                hit = tags.get(_norm(f"plate:{cand}"))
                if hit is not None:
                    break
            if hit is not None:
                entries = [hit]
    out: list[Path] = []
    for e in entries:
        p = _first_existing([
            # the picker's deterministic project copy first (stable), then the
            # raw name (hand-written manifests), then the batch still itself
            _project_copy(pid, "chars", cid, e.get("copied") or ""),
            _project_copy(pid, "chars", cid, e.get("file", "")),
            _batch_file(e, "face"),
        ])
        if p and p not in out:
            out.append(p)
    if out:
        return out
    if loadout:
        # a tagged still existed but nothing resolved — fall back to the
        # untagged identity chain rather than losing the character entirely
        return character_refs(pid, cid, char, None, shot=shot)
    # existing project picks / auto identity (kept as the fallback chain so
    # projects that predate reference_images keep working unchanged)
    p = None
    if is_safe_component(str(pid)) and is_safe_component(str(cid)):
        cdir = _bible_dir() / "projects" / pid / "refs" / "chars" / cid
        p = _first_existing([cdir / "selected.png"])
        if p is None:
            imgs = _dir_images(cdir)
            p = imgs[0] if imgs else None
    if p is not None:
        out.append(p)
    if not out:
        from shot_images import auto_identity_files, resolve_identity_path
        for name in auto_identity_files(pid, cid):
            hit = resolve_identity_path(pid, cid, name)
            if hit is not None and hit.exists():
                out.append(hit)
                break
    return out


def weapon_refs(pid: str, cid: str, wid: str, weapon: dict | None) -> Path | None:
    """The weapon's design still (weapon-only or in-hand), if one exists.

    Weapons are EXTRA pictures: the composite loadout still already carries
    the weapon in-hand, so these only ride along on models with spare
    reference capacity (H3), lead character first.
    """
    for e in _ref_entries(weapon, want="weapon"):
        p = _first_existing([
            _power_copy(pid, cid, f"weapon_{wid}", e.get("copied") or ""),
            _power_copy(pid, cid, f"weapon_{wid}", e.get("file", "")),
            _batch_file(e, "weapon"),
        ])
        if p is not None:
            return p
    return None


def _loadout_name(char: dict | None, shot_char: dict | None,
                  shot: dict | None) -> str:
    """Which named loadout this character wears in this shot.

    Order: per-shot override -> the character's scene map -> beat-text match
    against loadout/weapon names -> "" (base outfit, no weapon).
    """
    explicit = str((shot_char or {}).get("loadout") or "").strip()
    if explicit:
        return explicit
    char = char or {}
    loadouts = char.get("loadouts") if isinstance(char.get("loadouts"), dict) else {}
    if not loadouts:
        return ""
    scene = str((shot or {}).get("scene") or "")
    smap = char.get("scene_tags") if isinstance(char.get("scene_tags"), dict) else {}
    if scene and smap.get(scene):
        return str(smap[scene]).strip()
    hay = _norm(" ".join([
        str((shot or {}).get("primary_action") or ""),
        str((shot or {}).get("narrative") or ""),
        str((shot or {}).get("beat") or ""),
        str((shot or {}).get("wardrobe") or ""),
    ]))
    if not hay:
        return ""
    for name in loadouts.keys():
        nn = _norm(name)
        if nn and nn in hay:
            return str(name)
    weapons = char.get("weapons") if isinstance(char.get("weapons"), dict) else {}
    for wid, w in weapons.items():
        wn = _norm(wid)
        if wn and wn in hay:
            for name, ld in loadouts.items():
                if isinstance(ld, dict) and str(ld.get("weapon") or "") == str(wid):
                    return str(name)
    return ""


def resolve_presentation(char: dict | None, shot_char: dict | None,
                         shot: dict | None) -> dict:
    """The character's text presentation for one shot (prompt + provenance).

    Returns `{loadout, outfit, weapon, weapon_txt, handling, sfx}`. Outfit and
    weapon TEXT always travel into the prompt whether or not a reference
    exists — references reinforce, they are never the only carrier.
    """
    char = char or {}
    name = _loadout_name(char, shot_char, shot)
    loadouts = char.get("loadouts") if isinstance(char.get("loadouts"), dict) else {}
    ld = loadouts.get(name) if name and isinstance(loadouts.get(name), dict) else {}
    outfits = char.get("outfits") if isinstance(char.get("outfits"), dict) else {}
    outfit = str(ld.get("outfit") or "").strip()
    if outfit and outfit in outfits and isinstance(outfits[outfit], dict):
        outfit = str(outfits[outfit].get("descriptor") or outfit)
    if not outfit:
        outfit = str(char.get("outfit") or "").strip()
    # explicit shot-level weapon (LLM/storygen) wins over the loadout default,
    # so a shot can carry a weapon without naming a whole loadout
    wid = str(ld.get("weapon") or (shot_char or {}).get("weapon") or "").strip()
    weapons = char.get("weapons") if isinstance(char.get("weapons"), dict) else {}
    w = weapons.get(wid) if wid and isinstance(weapons.get(wid), dict) else {}
    weapon_txt = str(w.get("descriptor") or "").strip()
    handling = str((shot_char or {}).get("handling") or "").strip()
    if not handling:
        hl = w.get("handling")
        handling = str(hl[0] if isinstance(hl, list) and hl else "").strip()
    return {"loadout": name, "outfit": outfit, "weapon": wid,
            "weapon_txt": weapon_txt, "handling": handling,
            "sfx": str(w.get("sfx") or "").strip()}


def power_refs(pid: str, cid: str, pw_id: str, power: dict | None,
               level: int | None = None) -> Path | None:
    """The power VFX still for one power at the requested intensity level.

    Entries are ordered by their `level` (default = list position + 1). The
    pick is the highest level <= the target (floor); no target -> the lowest.
    """
    entries = _ref_entries(power, want="power")
    if not entries:
        return None
    lv: list[tuple[int, dict]] = []
    for i, e in enumerate(entries):
        try:
            lvl = int(e.get("level"))
        except Exception:
            lvl = i + 1
        lv.append((lvl, e))
    lv.sort(key=lambda x: x[0])
    target = None
    if level not in (None, ""):
        try:
            target = int(level)
        except Exception:
            target = None
    if target is None:
        pick = lv[0][1]
    else:
        below = [x for x in lv if x[0] <= target]
        pick = (below[-1] if below else lv[0])[1]
    return _first_existing([
        _power_copy(pid, cid, pw_id, pick.get("copied") or ""),
        _power_copy(pid, cid, pw_id, pick.get("file", "")),
        _batch_file(pick, "power"),
    ])


def location_refs(pid: str, lid: str, loc: dict | None,
                  tag: str | None = None) -> list[Path]:
    """Environment stills for one location, honouring a variant tag."""
    entries = _ref_entries(loc, want="environment")
    if tag:
        want = _norm(tag)
        hit = next((e for e in entries if _norm(e.get("tag")) == want), None)
        if hit is None:
            hit = next((e for e in entries
                        if want and want in _norm(e.get("tag"))), None)
        if hit is not None:
            entries = [hit]
    out: list[Path] = []
    for e in entries:
        p = _first_existing([
            _project_copy(pid, "locs", lid, e.get("copied") or ""),
            _project_copy(pid, "locs", lid, e.get("file", "")),
            _batch_file(e, "environment"),
        ])
        if p and p not in out:
            out.append(p)
    if out:
        return out
    if tag:
        return []                     # a requested variant does not exist
    if not is_safe_component(str(lid)):
        return []                     # shot JSON is client-written
    p = None
    if is_safe_component(str(pid)):
        ldir = _bible_dir() / "projects" / pid / "refs" / "locs" / lid
        p = _first_existing([ldir / "selected.png"])
        if p is None:
            imgs = _dir_images(ldir)
            p = imgs[0] if imgs else None
    if p is not None:
        out.append(p)
    if not out:
        for cand in _dir_images(ROOT / "roster" / "datasets" / "environment" / lid) \
                + _dir_images(ROOT / "roster" / "datasets" / "environment" / lid / "stills"):
            out.append(cand)
            break
    return out


def resolve_batch_path(entry: dict) -> Path | None:
    """Public wrapper: resolve a `{type,name,file}` batch reference to disk.

    Used by the Video Studio, whose picker knows a batch image by its
    type/name/file triple, not by an absolute path.
    """
    return _batch_file(entry, str(entry.get("type") or "face"))


def resolve_reference_entry(entry: dict) -> Path | None:
    """Resolve one reference spec: `{path}` (absolute/local) or `{type,name,file}`.

    `path` is client-supplied: it must lie inside the studio's media roots
    (core.resolve_user_path — never UNC). A refused path counts as missing.
    """
    p = entry.get("path")
    if p:
        try:
            rp = resolve_user_path(p, must_exist=False)
        except InvalidInput as e:
            log.warning("ltx_refs: reference path refused: %s", e)
            rp = None
        if rp is not None and rp.exists():
            return rp
    return resolve_batch_path(entry)


def resolve_reference_set(shot: dict, bible=None,
                          family: str | None = None) -> tuple[list[dict], list[str]]:
    """Resolve a shot to reference slots for the target model family.

    Returns `(refs, warnings)` where refs is a list of
    `{"slot": "pic1"|..., "path": <abs path>, "source": "<provenance>"}` in slot
    order, ready to hand to `video_studio.start(references=...)`.

    Budget: LTX = 4 subjects + background (MSR hard limit); H3 = 5 subjects +
    background (6 pictures). The environment takes `background`; the shot's
    power takes a subject slot; each character costs exactly ONE slot via its
    loadout composite still. Weapon-only stills ride along as extras on H3
    when capacity remains.
    """
    pid = str((shot or {}).get("project_id") or "")
    h3 = str(family or "").startswith("h3")
    subj_slots = SLOT_SUBJECTS_H3 if h3 else SLOT_SUBJECTS
    capacity = len(subj_slots) + 1          # + the background slot
    refs: list[dict] = []
    warnings: list[str] = []

    try:
        bchars = dict((bible.characters() if bible else {}) or {})
    except Exception as e:  # noqa: BLE001
        log.warning("ltx_refs: bible.characters() failed: %s", e)
        bchars = {}
    try:
        blocs = dict((bible.locations() if bible else {}) or {})
    except Exception as e:  # noqa: BLE001
        log.warning("ltx_refs: bible.locations() failed: %s", e)
        blocs = {}
    # case-tolerant lookups: a shot written with "Vladimir" must still find the
    # bible entry id'd "vladimir" (and vice versa) — an id-case mismatch used to
    # silently drop the identity/power slots with only a warning.
    bchars_l = {str(k).lower(): (str(k), v) for k, v in bchars.items()}
    blocs_l = {str(k).lower(): (str(k), v) for k, v in blocs.items()}

    def _bsrc(cid: str) -> tuple[str, dict | None]:
        ch = bchars.get(cid)
        if ch is None:
            hit = bchars_l.get(str(cid).lower())
            if hit:
                return hit
        return cid, ch

    chars = [c for c in (shot.get("characters") or [])
             if isinstance(c, dict) and c.get("id")]
    chars.sort(key=lambda c: TIER_ORDER.get(str(c.get("tier") or "crowd"), 9))

    presentations: list[tuple[str, dict, dict]] = []   # (canon, char, pres)
    for c in chars:
        if len(refs) >= len(subj_slots):
            warnings.append(
                f"more than {len(subj_slots)} subject references in the shot; "
                f"'{c.get('id')}' and any after it were not given a reference slot")
            break
        cid = str(c["id"])
        if str(c.get("tier") or "") == "crowd":
            warnings.append(f"crowd character {cid} skipped (no reference slot)")
            continue
        canon, char_obj = _bsrc(cid)
        pres = resolve_presentation(char_obj, c, shot)
        presentations.append((canon, char_obj or {}, pres))
        paths = character_refs(pid, canon, char_obj,
                               pres.get("loadout") or None, shot=shot)
        if paths:
            src = f"character:{canon}"
            if pres.get("loadout"):
                src += f":{pres['loadout']}"
            refs.append({"slot": subj_slots[len(refs)], "path": str(paths[0]),
                         "source": src})
        else:
            warnings.append(f"character {cid} has no usable reference image")

    # ---- power: the shot's power at its intensity level -> next subject slot
    pw_id = str((shot or {}).get("power") or "").strip()
    if pw_id:
        owner = None
        for c in chars:
            canon, ch = _bsrc(str(c.get("id")))
            powers = ch.get("powers") if isinstance(ch, dict) else None
            if isinstance(powers, dict) and pw_id in powers:
                owner = (canon, powers.get(pw_id))
                break
        if owner is None:
            warnings.append(f"power '{pw_id}' is not defined on any character "
                            f"in the shot — no power reference used")
        elif len(refs) >= len(subj_slots):
            warnings.append(f"power '{pw_id}' skipped: no free subject slot")
        else:
            p = power_refs(pid, owner[0], pw_id, owner[1],
                           (shot or {}).get("power_level"))
            if p:
                lvl = (shot or {}).get("power_level")
                refs.append({"slot": subj_slots[len(refs)], "path": str(p),
                             "source": f"power:{owner[0]}:{pw_id}"
                                       + (f":lv{lvl}" if lvl not in (None, "") else "")})
            else:
                warnings.append(f"power '{pw_id}' has no usable reference image "
                                f"(level {shot.get('power_level')})")

    lid = str((shot or {}).get("location") or "")
    if lid:
        loc = blocs.get(lid)
        if loc is None:
            hit = blocs_l.get(lid.lower())
            if hit:
                lid, loc = hit
        loc = loc or {}
        tag = str((shot or {}).get("location_tag") or "").strip()
        if not tag:
            scene = str((shot or {}).get("scene") or "")
            smap = loc.get("scene_tags") if isinstance(loc, dict) else None
            if isinstance(smap, dict) and scene:
                tag = str(smap.get(scene) or "").strip()
        paths = location_refs(pid, lid, loc, tag or None)
        if paths:
            refs.append({"slot": "background", "path": str(paths[0]),
                         "source": f"location:{lid}" + (f":{tag}" if tag else "")})
        else:
            warnings.append(f"location {lid} has no usable reference image"
                            + (f" for variant '{tag}'" if tag else ""))

    # ---- weapon extras (H3 only): a design still for a character's weapon
    # rides along when capacity remains — the lead character first. The
    # weapon may only take a FREE SUBJECT slot: assigning it "background"
    # collided with the environment reference (first-wins slot dedupe in
    # video_studio silently dropped one of them, and a free pic slot was
    # left unused).
    if h3:
        used_slots = {str(r.get("slot") or "") for r in refs}
        for canon, char_obj, pres in presentations:
            free = [s for s in subj_slots if s not in used_slots]
            if not free:
                break
            wid = str(pres.get("weapon") or "")
            if not wid:
                continue
            w = (char_obj.get("weapons") or {}).get(wid)
            p = weapon_refs(pid, canon, wid, w if isinstance(w, dict) else {})
            if p:
                refs.append({"slot": free[0], "path": str(p),
                             "source": f"weapon:{canon}:{wid}"})
                used_slots.add(free[0])

    # ---- duplicate guard: one image must never fill two slots
    seen: dict[str, str] = {}
    deduped: list[dict] = []
    for r in refs:
        key = str(r.get("path", "")).lower()
        if key and key in seen:
            warnings.append(f"reference '{Path(key).name}' was resolved for both "
                            f"{seen[key]} and {r['slot']} — the duplicate was "
                            f"dropped (use a different image per role)")
            continue
        seen[key] = r["slot"]
        deduped.append(r)
    refs = deduped

    if not refs:
        warnings.append("no references resolved — the shot will render as "
                        "plain text-to-video")
    for w in warnings:
        log.warning("[ltx_refs] %s", w)
    return refs, warnings


def add_continuation(refs: list[dict], tail, family: str) -> tuple[list[dict], str]:
    """Attach the previous shot's tail frame as a continuity reference.

    H3: slot `continuation` — video_studio pins it as the frame-0 anchor
    (MiniMaxH3AddGuide), so the clip opens exactly on the previous shot's
    final frame; identity still comes from the subject pictures.
    LTX: the tail takes the last free subject slot and the reference legend
    describes it as the continuation frame.

    Returns `(refs, note)`. `note` is "" when the tail was attached, else a
    human-readable reason it was skipped (callers log it as a warning).
    """
    if not tail:
        return refs, ""
    try:
        # client-supplied on the Video Studio route: media roots only, no UNC
        p = resolve_user_path(str(tail), must_exist=False)
    except InvalidInput as e:
        log.warning("ltx_refs: continuity tail refused: %s", e)
        return refs, "continuity tail missing on disk"
    if not p.exists():
        return refs, "continuity tail missing on disk"
    has_subject = any(str(r.get("slot") or "").startswith("pic") for r in refs)
    if not has_subject:
        # both graphs anchor on a subject picture; a tail alone cannot be
        # wired (the H3 t2v graph has no guide node, and the LTX MSR guide
        # hard-requires pic1)
        return refs, ("continuity tail skipped: no subject reference for "
                      "the anchor")
    fam = str(family or "")
    if fam.startswith("h3"):
        out = [r for r in refs if str(r.get("slot")) != "continuation"]
        out.append({"slot": "continuation", "path": str(p),
                    "source": "continuation:prev_tail"})
        return out, ""
    used = {str(r.get("slot") or "") for r in refs}
    free = [s for s in SLOT_SUBJECTS[1:] if s not in used]
    if not free:
        return refs, "continuity tail skipped: no free LTX reference slot"
    out = list(refs)
    out.append({"slot": free[-1], "path": str(p),
                "source": "continuation:prev_tail"})
    return out, ""
