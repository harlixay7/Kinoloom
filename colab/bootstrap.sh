#!/usr/bin/env bash
# =============================================================================
# Kinoloom worker bootstrap for Google Colab (T4) — idempotent, re-runnable.
#
# Turn a fresh GPU runtime into a registered render worker of the studio:
#   repo clone -> ComfyUI ee71d5c + pinned custom nodes + tracked patches
#   -> venv (inherits Colab's torch) -> model group fetch from HF
#   -> Tailscale userspace mesh -> worker_agent up -> registered on the PC.
#
# Required Colab Secrets / env:
#   HF_TOKEN          read token for the private HF model repo
#   TAILSCALE_AUTHKEY auth key (tag ephemeral, reusable)
#   WORKER_TOKEN      the studio's workers.shared_token (Worker PCs page/token API)
#   MAIN_URL          the PC control room over the tailnet, e.g.
#                     http://100.x.y.z:8080  (PC: `tailscale ip -4`)
# Optional env:
#   WORKER_NAME   (default kinoloom-colab)   MODEL_GROUPS (default h3_shared,h3_dit_singularity)
#   REPO_URL      (default https://github.com/harlixay7/Kinoloom.git)
#   GITHUB_PAT    read-only PAT, only for cloning a private fork
#   SELFTEST_NODES (comma list; default: H3 node classes)
#
# Re-running after a session death is THE recovery path: every step is
# guarded and model fetches resume/skip.
# =============================================================================
set -euo pipefail

AS_ROOT="${AS_ROOT:-/content/kinoloom}"
REPO_URL="${REPO_URL:-https://github.com/harlixay7/Kinoloom.git}"
WORKER_NAME="${WORKER_NAME:-kinoloom-colab}"
MODEL_GROUPS="${MODEL_GROUPS:-h3_shared,h3_dit_singularity}"
COMFY_COMMIT="ee71d5c"          # ComfyUI v0.36.0 — docs/setup/PINNED_VERSIONS.md
UPSCALER_REPO="https://github.com/LBH-123-AI/Comfyui_Minimax_h3_latent_Upscaler"
UPSCALER_COMMIT="40316cf"
MSR_REPO="https://github.com/liconstudio/ComfyUI-LTX2.5-MSR.git"
MSR_COMMIT="9894117"

log() { printf '\n\033[1;36m[bootstrap]\033[0m %s\n' "$*"; }
fail() { printf '\n\033[1;31m[bootstrap:FAIL]\033[0m %s\n' "$*" >&2; exit 1; }

# ------------------------------------------------------------------ 0. sanity
SMOKE="${SMOKE:-0}"
# smoke mode runs without a studio: keep `set -u` from aborting on these
MAIN_URL="${MAIN_URL:-}"
WORKER_TOKEN="${WORKER_TOKEN:-}"
log "0/7 sanity"
nvidia-smi -L >/dev/null 2>&1 || fail "no GPU visible — select a GPU runtime (Runtime > Change runtime type > T4)"
[ -n "${HF_TOKEN:-}" ]        || fail "HF_TOKEN secret not set"
if [ "$SMOKE" != "1" ]; then
  [ -n "${WORKER_TOKEN:-}" ]  || fail "WORKER_TOKEN secret not set (Worker PCs page -> New token)"
  [ -n "${MAIN_URL:-}" ]      || fail "MAIN_URL not set — the PC control room over the tailnet, e.g. http://100.x.y.z:8080"
  case "$MAIN_URL" in
    http://127.*|http://localhost*) fail "MAIN_URL must be the PC's TAILNET address, not localhost (on the PC: tailscale ip -4)" ;;
  esac
fi

# --------------------------------------------------------------- 1. repo sync
log "1/7 repo -> $AS_ROOT"
if [ -d "$AS_ROOT/.git" ]; then
  git -C "$AS_ROOT" fetch origin >/dev/null 2>&1 || true
  git -C "$AS_ROOT" reset --hard origin/HEAD >/dev/null 2>&1 \
    || git -C "$AS_ROOT" reset --hard origin/main
elif [ -n "${GITHUB_PAT:-}" ]; then
  # a private fork: clone with the PAT, then never keep it in .git/config
  git clone "https://x-access-token:${GITHUB_PAT}@${REPO_URL#https://}" "$AS_ROOT"
  git -C "$AS_ROOT" remote set-url origin "$REPO_URL"
else
  git clone "$REPO_URL" "$AS_ROOT"
fi
git -C "$AS_ROOT" log --oneline -1

# ----------------------------------------------- 2. tailscale (userspace)
log "2/7 tailscale"
ENVSH="$AS_ROOT/colab/colab_env.sh"
cat > "$ENVSH" <<EOF
# generated by bootstrap.sh — sourced before starting the agent
export MAIN_URL="${MAIN_URL}"
export HF_TOKEN="${HF_TOKEN}"
export WORKER_TOKEN="${WORKER_TOKEN}"
export NO_PROXY="127.0.0.1,localhost,::1"
export no_proxy="127.0.0.1,localhost,::1"
EOF
PUBLIC_BASE_URL=""
if [ -n "${TAILSCALE_AUTHKEY:-}" ]; then
  if ! command -v tailscale >/dev/null 2>&1; then
    curl -fsSL https://tailscale.com/install.sh | sh >/dev/null
  fi
  if ! pgrep -f "tailscaled" >/dev/null 2>&1; then
    # Colab containers have no CAP_NET_ADMIN: userspace netstack only.
    # Outbound tailnet traffic needs the proxy env (written below); inbound
    # works via tailscale serve (netstack-native, no TUN involved).
    nohup tailscaled --tun=userspace-networking \
      --socks5-server=localhost:1055 \
      --outbound-http-proxy-listen=localhost:1056 \
      >"$AS_ROOT/colab/tailscaled.log" 2>&1 &
    sleep 3
  fi
  tailscale up --auth-key="${TAILSCALE_AUTHKEY}" \
    --hostname="${WORKER_NAME}" --accept-dns=false --ephemeral \
    >"$AS_ROOT/colab/tailscale_up.log" 2>&1
  cat >> "$ENVSH" <<'EOF'
export HTTP_PROXY="http://127.0.0.1:1056"
export HTTPS_PROXY="http://127.0.0.1:1056"
export http_proxy="http://127.0.0.1:1056"
export https_proxy="http://127.0.0.1:1056"
EOF
  TS_IP="$(tailscale ip -4 | head -1)"
  SELF_DNS="$(tailscale status --json | python3 -c \
    "import json,sys;print(json.load(sys.stdin)['Self']['DNSName'].rstrip('.'))" \
    2>/dev/null || true)"
  # Preferred inbound: tailscale serve (TLS, netstack-native). Fallback: the
  # raw tailnet IP (works when the netstack forwards same-port inbound).
  if [ -n "$SELF_DNS" ] && tailscale serve --bg 8120 \
      >"$AS_ROOT/colab/tailscale_serve.log" 2>&1; then
    PUBLIC_BASE_URL="https://${SELF_DNS}"
    log "tailscale up: ip=${TS_IP} serve=${PUBLIC_BASE_URL}"
  else
    PUBLIC_BASE_URL="http://${TS_IP}:8120"
    log "tailscale up: ip=${TS_IP}; serve FAILED (see tailscale_serve.log) — registering raw IP; the PC Workers-page Test will confirm reachability"
  fi
  # reachability proof towards the PC control room (worker mode only). The
  # userspace netstack has no route to tailnet IPs: go through its HTTP proxy,
  # as the agent will (colab_env.sh). /api/health is the public probe; any
  # other route answers 401 without the API token.
  if [ "$SMOKE" != "1" ]; then
    if curl -sf -o /dev/null --max-time 15 -x http://127.0.0.1:1056 \
        "${MAIN_URL%/}/api/health"; then
      log "PC control room reachable over the tailnet"
    else
      fail "cannot reach MAIN_URL=${MAIN_URL} — is Tailscale up on the PC and is MAIN_URL its tailnet IP?"
    fi
  else
    log "smoke mode: tailscale up (ip=${TS_IP}) — probe PC→worker reachability manually"
  fi
else
  log "TAILSCALE_AUTHKEY not set — registering LAN IP (will NOT be reachable from the PC on Colab; set the authkey)"
fi

# --------------------------------------------------------- 3. ComfyUI build
log "3/7 ComfyUI @ ${COMFY_COMMIT} + pinned custom nodes"
cd "$AS_ROOT"
if [ ! -d ComfyUI/.git ]; then
  git clone https://github.com/comfyanonymous/ComfyUI.git ComfyUI
fi
CURR="$(git -C ComfyUI rev-parse --short HEAD || true)"
if [ "$CURR" != "$COMFY_COMMIT" ]; then
  git -C ComfyUI fetch origin >/dev/null 2>&1 || true
  git -C ComfyUI checkout "$COMFY_COMMIT"
fi
# pinned upstream packs (not tracked in git — docs/setup/PINNED_VERSIONS.md)
if [ ! -d ComfyUI/custom_nodes/Comfyui_Minimax_h3_latent_Upscaler/.git ]; then
  git clone "$UPSCALER_REPO" ComfyUI/custom_nodes/Comfyui_Minimax_h3_latent_Upscaler
fi
git -C ComfyUI/custom_nodes/Comfyui_Minimax_h3_latent_Upscaler checkout "$UPSCALER_COMMIT" >/dev/null 2>&1 || true
if [ ! -d ComfyUI/custom_nodes/ComfyUI-LTX2.5-MSR/.git ]; then
  git clone "$MSR_REPO" ComfyUI/custom_nodes/ComfyUI-LTX2.5-MSR
fi
git -C ComfyUI/custom_nodes/ComfyUI-LTX2.5-MSR checkout "$MSR_COMMIT" >/dev/null 2>&1 || true
# tracked local modifications from the repo (lab packs + core mod)
cp -f ComfyUI_LTX/custom_nodes/Comfyui_Minimax_h3_latent_Upscaler/nodes/MMH3_Split_Upscale.py \
      ComfyUI/custom_nodes/Comfyui_Minimax_h3_latent_Upscaler/nodes/ 2>/dev/null || true
cp -rf ComfyUI_LTX/custom_nodes/ComfyUI-LTX25-Studio ComfyUI/custom_nodes/ 2>/dev/null || true
cp -f ComfyUI_LTX/comfy_extras/nodes_lt_audio.py ComfyUI/comfy_extras/ 2>/dev/null || true

# generated model paths — mirrors ComfyUI_LTX/extra_model_paths.yaml
cat > ComfyUI/extra_model_paths.yaml <<EOF
kinoloom:
    base_path: ${AS_ROOT}/models
    diffusion_models: diffusion_models
    text_encoders: text_encoders
    vae: vae
    latent_upscale_models: latent_upscale_models
    loras: loras
    checkpoints: checkpoints
    upscale_models: upscale_models
    clip: clip
EOF

# ------------------------------------------------------ 4. venv + deps (D2)
log "4/7 venv (inherits Colab's torch) + ComfyUI deps"
if [ ! -x .colab-venv/bin/python ]; then
  python3 -m venv --system-site-packages .colab-venv
fi
PIP=".colab-venv/bin/python -m pip -q"
$PIP install --upgrade pip >/dev/null 2>&1 || true
$PIP install -r ComfyUI/requirements.txt
$PIP install gguf pyyaml || true
$PIP install comfy-kitchen 2>/dev/null || log "comfy-kitchen not on PyPI — the smoke test will flag it if H3 needs it"
for rq in ComfyUI/custom_nodes/*/*/requirements.txt \
          ComfyUI/custom_nodes/*/requirements.txt; do
  [ -f "$rq" ] && $PIP install -r "$rq" || true
done

# ------------------------------------------------- 5. model groups (HF pull)
log "5/7 model groups: ${MODEL_GROUPS}"
mkdir -p models
source "$ENVSH"
python3 colab/fetch_models.py --groups "$MODEL_GROUPS" --models-dir "$AS_ROOT/models"

# ----------------------------------------------------- 6. worker_config.yaml
log "6/7 worker_config.yaml"
SELFTEST_NODES="${SELFTEST_NODES:-UNETLoader,CLIPLoader,VAELoader,MiniMaxH3ReferenceToVideo,ModelAttentionBackend,MinimaxH3LatentUpscaler3D,MMH3SplitUpscale,ManualSigmas,SamplerCustomAdvanced,SaveVideo}"
python3 - "$AS_ROOT" "$WORKER_NAME" "$MAIN_URL" "$WORKER_TOKEN" \
          "$PUBLIC_BASE_URL" "$HF_TOKEN" "$MODEL_GROUPS" "$SELFTEST_NODES" <<'PYEOF'
import sys, yaml
from pathlib import Path
root, name, main_url, token, pub, hf_tok, groups, nodes = sys.argv[1:9]
manifest = {}
mp = Path(root) / "install" / "colab_model_groups.json"
try:
    manifest = __import__("json").loads(mp.read_text(encoding="utf-8"))
except Exception:
    pass
required = []
for g in groups.split(","):
    for f in (manifest.get("groups", {}).get(g.strip(), {}) or {}).get("files", []):
        required.append(str(f["path"]))
cfg = {
    "name": name,
    "main_url": main_url.rstrip("/"),
    "token": token,
    "agent_port": 8120,
    "comfyui_port": 8188,
    "autostart_comfy": True,
    "heartbeat_s": 10,
    "comfyui_dir": f"{root}/ComfyUI",
    "models_dir": f"{root}/models",
    "python": f"{root}/.colab-venv/bin/python",
    "comfy_args": [],
    "public_base_url": pub,
    "hf_token": hf_tok,
    "roles": ["video", "image", "upscale"],
    "require_models": bool(required),
    "required_models": required,
    "selftest_nodes": [n for n in nodes.split(",") if n],
}
out = Path(root) / "tool" / "worker" / "worker_config.yaml"
out.write_text(yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
print(f"wrote {out} (required_models={len(required)})")
PYEOF

# ---------------------------------------------------------- 7. agent + verify
if [ "$SMOKE" = "1" ]; then
  log "SMOKE mode — worker agent not started; ComfyUI + models are ready for the smoke cells"
  exit 0
fi
log "7/7 starting worker agent"
pkill -f "worker_agent.py" 2>/dev/null || true
sleep 1
source "$ENVSH"
nohup "$AS_ROOT/.colab-venv/bin/python" "$AS_ROOT/tool/worker/worker_agent.py" \
  >> "$AS_ROOT/colab/agent.out" 2>&1 &
for i in $(seq 1 30); do
  if curl -s --max-time 3 http://127.0.0.1:8120/ping >/dev/null 2>&1; then break; fi
  sleep 1
done
curl -s http://127.0.0.1:8120/ping || fail "agent did not come up — see colab/agent.out"
sleep 2
echo "----- agent log (registration) -----"
tail -5 "$AS_ROOT/colab/agent.out" || true
echo "------------------------------------"
log "DONE — worker '$WORKER_NAME' should appear ONLINE on the PC Worker PCs page"
log "advertised: ${PUBLIC_BASE_URL:-LAN IP (unreachable on Colab!)}  main: ${MAIN_URL}"
log "job flow: PC UI -> assign worker '${WORKER_NAME}' -> renders land in output/ as usual"
